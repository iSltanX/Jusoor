/**
 * الكتابة في حافظة النظام.
 *
 * تعيش في `ui` لا في `browser/`: `navigator.clipboard` واجهة ويب قياسية لا
 * `chrome.*`، وحصر `browser/` يخص واجهات المتصفح-كإضافة وحدها (قرار 0005).
 * وهي مشروطة بإيماءة مستخدم، فموضعها الطبيعي معالج النقر في طبقة العرض.
 *
 * **لا تُلقي**: تعذّر النسخ حالة متوقعة لا عطل — قد يمنع المتصفح الكتابة في
 * الحافظة بحسب التركيز أو السياق. النتيجة المنطقية تُعرض للمستخدم بصدق مع بقاء
 * النص كاملًا أمامه لينسخه يدويًا (دستور المنتج §6.6 و§13.3)، بدل ادعاء نجاح
 * لم يقع أو ابتلاع الفشل صامتًا.
 */
export async function writeToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text)
    return true
  } catch {
    return false
  }
}
